"""Export, for every single-edit evolution of the benchmark policy sets,
the concrete regression tests generated by TPG-Reg+D (seed 1) with the
decisions of both versions and the decisive rules, and the impact analysis
(changed rules, BIS, affected rules).

Usage: python3 export_regression_suites.py <out dir>
Output: <SET>_regression_tests.csv, <SET>_impact_sets.csv
"""
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), ".."))

import csv, json, os, sys
import numpy as np
from tpgreg.policy_model import Grid, evaluate, DEC_NAME
from tpgreg.benchmarks import DATASETS
from tpgreg.mutation import evolutions
from tpgreg.typed_policy_graph import TPG
from tpgreg.impact_analysis import diff_bis
from tpgreg.test_generation import tpg_obligations, minimise

OUT = sys.argv[1] if len(sys.argv) > 1 else "../results/regression_suites"
os.makedirs(OUT, exist_ok=True)
FULL = ("precedes", "overrides", "scopes", "refers")
for name, (mk, dom) in DATASETS.items():
    G = Grid(dom)
    ps1 = mk()
    g1 = TPG(ps1, G)
    attrs = list(dom)
    f = open(f"{OUT}/{name}_regression_tests.csv", "w", newline="")
    w = csv.writer(f)
    w.writerow(["evolution", "op", "edit", "test"] + attrs + ["decision_v1", "decision_v2", "changed", "decisive_rules"])
    fi = open(f"{OUT}/{name}_impact_sets.csv", "w", newline="")
    wi = csv.writer(fi)
    wi.writerow(["evolution", "op", "edit", "behaviour_changed", "changed_requests", "CH", "BIS", "affected_rules", "affected_outside_BIS", "suite_size", "detected"])
    for k, evo in enumerate(evolutions(ps1, dom)):
        ps2 = evo["ps"]
        ev2 = evaluate(ps2, G)
        g2 = TPG(ps2, G, ev2)
        CH, bis, cs, fol = diff_bis(g1, g2, FULL)
        diff = g1.ev.dec != ev2.dec
        obl = tpg_obligations(g1, g2, CH, bis, cs, fol, FULL)
        dobl = [diff & ((g1.ev.app[r] if r in g1.ev.app else False) | (ev2.app[r] if r in ev2.app else False)) for r in sorted(bis)]
        suite = minimise(obl + [m for m in dobl if np.any(m)], np.random.default_rng(1000 + k))
        aff = sorted({r for r, m in g1.ev.decisive.items() if (m & diff).any()} | {r for r, m in ev2.decisive.items() if (m & diff).any()})
        for t, q in enumerate(suite):
            req = G.request(q)
            dec = sorted({r for r, m in g1.ev.decisive.items() if m[q]} | {r for r, m in ev2.decisive.items() if m[q]})
            w.writerow([k, evo["op"], evo["desc"], t] + [req[a] for a in attrs] +
                       [DEC_NAME[int(g1.ev.dec[q])], DEC_NAME[int(ev2.dec[q])], int(diff[q]), " ".join(dec)])
        wi.writerow([k, evo["op"], evo["desc"], int(diff.any()), int(diff.sum()), " ".join(sorted(CH)), " ".join(sorted(bis)),
                     " ".join(aff), len(set(aff) - bis), len(suite), int(bool(len(suite)) and bool(diff[np.array(suite)].any()))])
    f.close(); fi.close()
    print(name, "exported", flush=True)
